// =========================================================
// configure()
// =========================================================
//
// Called by Nav2 Controller Server when the controller plugin
// is created.
//
// This is where we:
//   - store the lifecycle node
//   - store TF buffer
//   - store costmap
//   - read controller parameters
//
// =========================================================

void PurePursuitController::configure(
  const rclcpp_lifecycle::LifecycleNode::WeakPtr & parent,
  std::string name,
  const std::shared_ptr<tf2_ros::Buffer> tf,
  const std::shared_ptr<nav2_costmap_2d::Costmap2DROS> costmap_ros)
{
  node_ = parent;

  plugin_name_ = name;

  tf_ = tf;

  costmap_ros_ = costmap_ros;

  auto node = node_.lock();

  // ---------------------------------------------------------
  // Read controller parameters from Nav2 YAML
  // ---------------------------------------------------------

  linear_velocity_ =
    node->declare_parameter<double>(
      plugin_name_ + ".linear_velocity",
      0.2);

  angular_gain_ =
    node->declare_parameter<double>(
      plugin_name_ + ".angular_gain",
      1.0);

  RCLCPP_INFO(
    node->get_logger(),
    "Pure Pursuit Controller configured");
}


// =========================================================
// cleanup()
// =========================================================
//
// Called when Nav2 unloads / cleans the controller.
//
// =========================================================

void PurePursuitController::cleanup()
{
  global_plan_.poses.clear();

  current_waypoint_index_ = 0;

  RCLCPP_INFO(
    node_.lock()->get_logger(),
    "Pure Pursuit Controller cleaned up");
}


